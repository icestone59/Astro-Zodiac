let quoteTimer = null;

function startQuoteRotator(targetElementId) {
    const target = document.getElementById(targetElementId);
    if (!target) return;

    let index = Math.floor(Math.random() * ASTRO_QUOTES.length);

    // แสดงประโยคแรกทันที
    target.innerHTML = `
        <div style="padding: 40px 20px; text-align: center; animation: fadeIn 0.5s ease-in-out;">
            <div style="font-size: 28px; margin-bottom: 16px;">🔮</div>
            <div style="color: #c084fc; font-size: 16px; font-weight: 500; line-height: 1.6; max-width: 600px; margin: 0 auto;">
                "${ASTRO_QUOTES[index]}"
            </div>
            <div style="color: #64748b; font-size: 12px; margin-top: 16px;">
                กำลังประมวลผลตำแหน่งดาวดาราศาสตร์และวิเคราะห์ศักยภาพ...
            </div>
        </div>
    `;

    if (quoteTimer) clearInterval(quoteTimer);

    // สลับประโยคทุกๆ 3,000 มิลลิวินาที (3 วินาที)
    quoteTimer = setInterval(() => {
        index = (index + 1) % ASTRO_QUOTES.length;
        const quoteText = target.querySelector("div > div:nth-child(2)");
        if (quoteText) {
            quoteText.style.opacity = '0';
            setTimeout(() => {
                quoteText.textContent = `"${ASTRO_QUOTES[index]}"`;
                quoteText.style.opacity = '1';
                quoteText.style.transition = 'opacity 0.5s ease-in-out';
            }, 250);
        }
    }, 3000);
}

function stopQuoteRotator() {
    if (quoteTimer) {
        clearInterval(quoteTimer);
        quoteTimer = null;
    }
}
